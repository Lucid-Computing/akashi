"""Provider-owned, seven-day storage for redacted engine telemetry (retention.md)."""

import json
import sqlite3
from collections.abc import Callable, Iterator
from contextlib import AbstractContextManager, closing, contextmanager
from datetime import datetime, timedelta, timezone
from pathlib import Path

from operations.private_db import private_database_file
from operations.telemetry import Event, Telemetry

_EPOCH = datetime(1970, 1, 1, tzinfo=timezone.utc)
_MICROSECOND = timedelta(microseconds=1)
_RETENTION_US = timedelta(days=7) // _MICROSECOND


def _utc_now() -> datetime:
    return datetime.now(timezone.utc)


class EngineLogs:
    """Store only records generated by the engine's allowlisted telemetry serializer."""

    def __init__(self, path: Path, *, clock: Callable[[], datetime] = _utc_now) -> None:
        private_database_file(path)
        self._path = path
        self._clock = clock
        self._telemetry = Telemetry(self._append)
        with self._db() as db:
            db.execute("PRAGMA journal_mode=DELETE")
            db.execute(
                "CREATE TABLE IF NOT EXISTS engine_logs ("
                "expires_us INTEGER NOT NULL, record TEXT NOT NULL)"
            )
            db.execute(
                "CREATE INDEX IF NOT EXISTS engine_logs_expiry "
                "ON engine_logs(expires_us)"
            )
        self.purged_on_open = self.sweep()

    @contextmanager
    def _db(self) -> Iterator[sqlite3.Connection]:
        with closing(sqlite3.connect(self._path)) as db, db:
            db.execute("PRAGMA secure_delete=ON")
            yield db

    def _now(self) -> int:
        now = self._clock()
        if now.utcoffset() is None:
            raise ValueError("engine log clock must be timezone-aware")
        return (now - _EPOCH) // _MICROSECOND

    @staticmethod
    def _expire(db: sqlite3.Connection, now: int) -> int:
        return db.execute(
            "DELETE FROM engine_logs WHERE expires_us <= ?", (now,)
        ).rowcount

    def _append(self, record: str) -> None:
        with self._db() as db:
            db.execute("BEGIN IMMEDIATE")
            now = self._now()
            self._expire(db, now)
            db.execute(
                "INSERT INTO engine_logs(expires_us,record) VALUES(?,?)",
                (now + _RETENTION_US, record),
            )

    def emit(self, event: Event) -> None:
        if type(event) is not Event or event.service != "engine":
            raise ValueError("expected a typed engine event")
        self._telemetry.emit(event)

    def stage(self, phase: str, *, mode: str = "live") -> AbstractContextManager[None]:
        return self._telemetry.stage("engine", phase, mode=mode)

    def read(self) -> list[dict[str, object]]:
        """Read unexpired entries in insertion order, even when cleanup is delayed."""
        with self._db() as db:
            db.execute("BEGIN IMMEDIATE")
            self._expire(db, self._now())
            return [
                json.loads(record)
                for (record,) in db.execute(
                    "SELECT record FROM engine_logs ORDER BY rowid"
                )
            ]

    def sweep(self) -> int:
        """Erase overdue entries and their SQLite payload bytes in one transaction."""
        with self._db() as db:
            db.execute("BEGIN IMMEDIATE")
            return self._expire(db, self._now())
